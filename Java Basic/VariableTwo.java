public class VariableTwo {
    public static void main(String[] args) {
        int a=10;
        float b=10.55f;
        char c='a';
        double d=10.567895;
        System.out.println("Integer: "+ a);
        System.out.println("Float: "+ b);
        System.out.println("Character: "+ c);
        System.out.println("Double Value: "+ d);
        
    } 
}
